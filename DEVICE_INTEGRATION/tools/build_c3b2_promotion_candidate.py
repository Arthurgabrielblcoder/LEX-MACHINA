"""C3B.2 CORRELATA promotion: SD overlay of the new physical baseline, built with the OFFICIAL staging generator (build_sd_staging).

Inputs (approved, read-only):
  - everything exactly as the physically approved FULL_CF_ENTENDA_810 package (same profile, same ENTENDA chain, runtime, TEXT_MAP)
  - REF_LOOKUP.IDX / REF_PAYLOAD.IDX and CF88_TARGETS.IDX: the C3B.2 bytes, byte-identical to the C3B.1 bytes that were tested
    physically (CORRELATA_COVERAGE_AUDIT/C3B2_PHYSICAL_TEST_PACKAGE/candidate). The generator would recompute every TARGETS flag; the
    approved file differs from that recomputation ONLY in flag position R ([4], not read by the firmware), which C3B.1 kept on purpose
    (only C was allowed to change). The approved bytes are kept and the R divergence is recorded, never "fixed" here.
  - LEXV1.VER and LEX_DEVICE_MANIFEST.json: regenerated by the generator itself (BUILD_ID = hash of the package files; GIT_COMMIT pinned to
    the commit that holds the approved C3B.2 bytes, so the package stays byte-reproducible after later commits).
Outputs: DEVICE_INTEGRATION/staging_sd_v1_c3b2_promotion_candidate/ (SD/99_LEX_V1 + SD/99_RELATIONS_V2 indices + _host/STAGING_FILE_MANIFEST.json).
Firmware: unchanged. Never writes to a removable volume. Usage: python build_c3b2_promotion_candidate.py [--runs N]
"""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DI = HERE.parent
ROOT = DI.parent
sys.path.insert(0, str(HERE))
import build_sd_staging as S  # noqa: E402
import build_full_entenda_810_candidate as F  # noqa: E402

PROFILE = F.PROFILE
OUT = DI / 'staging_sd_v1_c3b2_promotion_candidate'
TMP = DI / '_tmp_c3b2_promotion_rebuild'
PKG = ROOT / 'CORRELATA_COVERAGE_AUDIT/C3B2_PHYSICAL_TEST_PACKAGE'
APPROVED_SD = PKG / 'candidate/SD'
PIN = ROOT / 'CORRELATA_COVERAGE_AUDIT/inputs/CORRELATA_EVIDENCE_PIN.json'     # physical manifest of the current approved card (810)
BUILD_COMMIT = '9f83c56ece824c867861f49a7c1ece29026a26a2'                      # holds the approved C3B.2 bytes (identical to tested C3B.1)
ENGINE_VERSION = dict(tag='cf-reference-engine-run4', run='run4', status='RUN4_C3B2_PHYSICALLY_APPROVED',
                      derived_from='run3 + CORRELATA overlay (C3A, C3A.1, C3B.1 fixes; C3B.2 = bytes physically tested as C3B.1)')
PHYSICALLY_TESTED = {   # C3B.1 physical test (2026-10-12), hashes read from the card
    '99_LEX_V1/10_TARGETS/CF88_TARGETS.IDX': 'd2fcc15bbe41ef16c51bbe1ef7cb201bd9677b6ac54198b96ad2abc08395e06c',
    '99_LEX_V1/20_REFERENCES/REF_LOOKUP.IDX': '27c67eea6a38e3cba012d4a3d02c3856d37fd4cd1bae15473854fab0edea5430',
    '99_LEX_V1/20_REFERENCES/REF_PAYLOAD.IDX': '1762642d337aff83ac5b95e074235bc58028b8a68bac17a384e9eed4a4a5addd',
    '99_RELATIONS_V2/05_INDICES_ESP32_V2/EXT_ARTIGOS.IDX': '5c54face7ea7eff62dbbb0a4193b5e2452e7fb03d82012d09919e74d234b3e5e',
    '99_RELATIONS_V2/05_INDICES_ESP32_V2/RELACOES.IDX': '691790f3ee5d4aaa9b88235bca33008357b99d87324c07b1da8b51355c20685c',
    '99_RELATIONS_V2/05_INDICES_ESP32_V2/REL_LOOKUP.IDX': 'efac06cee0a1d8f0676564ba128d0ab8f474b89399f40de6422cc6fded37ef2c',
}
EXPECTED_CHANGED = ('00_SYS/LEXV1.VER', '00_SYS/LEX_DEVICE_MANIFEST.json', '10_TARGETS/CF88_TARGETS.IDX', '20_REFERENCES/REF_LOOKUP.IDX',
                    '20_REFERENCES/REF_PAYLOAD.IDX')


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def approved_bytes():
    out = {}
    for rel, want in PHYSICALLY_TESTED.items():
        b = (APPROVED_SD / rel).read_bytes()
        if hashlib.sha256(b).hexdigest() != want:
            raise SystemExit(f'APPROVED_BYTES_MISMATCH {rel}')
        out[rel] = b
    return out


def build(out):
    """Official generator; only the TARGETS table is replaced by the physically tested bytes, after proving the difference is R-only."""
    approved = approved_bytes()
    original = S.build_targets
    record = {}

    def targets_with_approved_bytes(sd, idx, status, entenda_lookup, ref_lookup):
        stats = original(sd, idx, status, entenda_lookup, ref_lookup)
        p = sd / '10_TARGETS/CF88_TARGETS.IDX'
        gen = p.read_bytes().decode('utf-8').split('\n')
        app = approved['99_LEX_V1/10_TARGETS/CF88_TARGETS.IDX'].decode('utf-8').split('\n')
        if len(gen) != len(app):
            raise SystemExit('TARGETS_SHAPE_DIFFERS')
        r_only = 0
        for g, a in zip(gen, app):
            if g == a:
                continue
            fg, fa = g.split('|'), a.split('|')
            if g.startswith('#') or fg[:3] != fa[:3] or fg[3][:4] != fa[3][:4] or fg[3][5:] != fa[3][5:]:
                raise SystemExit(f'TARGETS_DIFFER_BEYOND_R {fg[0]}')
            r_only += 1
        p.write_bytes(approved['99_LEX_V1/10_TARGETS/CF88_TARGETS.IDX'])
        record['targets_r_only_divergence_vs_generator'] = r_only
        return stats

    S.build_targets = targets_with_approved_bytes
    try:
        man = S.build(out, ref_dir=APPROVED_SD / '99_LEX_V1/20_REFERENCES', require_committed_refs=True, reference_engine_version=ENGINE_VERSION,
                      profile=PROFILE, build_commit=BUILD_COMMIT)
    finally:
        S.build_targets = original
    rel_dir = Path(out) / 'SD/99_RELATIONS_V2/05_INDICES_ESP32_V2'
    rel_dir.mkdir(parents=True)
    for rel, b in approved.items():
        if rel.startswith('99_RELATIONS_V2/'):
            (Path(out) / 'SD' / rel).write_bytes(b)
    return man, record


def tree(d):
    return {p.relative_to(d).as_posix(): sha(p) for p in sorted(Path(d).rglob('*')) if p.is_file()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs', type=int, default=3)
    a = ap.parse_args()
    man, rec = build(OUT)
    trees = [tree(OUT / 'SD')]
    try:
        for _ in range(a.runs - 1):
            build(TMP)
            trees.append(tree(TMP / 'SD'))
    finally:
        shutil.rmtree(TMP, ignore_errors=True)
    if not all(t == trees[0] for t in trees):
        raise SystemExit('STAGING_NOT_DETERMINISTIC')
    phys = json.loads(PIN.read_text(encoding='utf-8'))['physical_sd']['files']
    files = []
    for rel, h in trees[0].items():
        p = OUT / 'SD' / rel
        files.append(dict(path='/' + rel, bytes=p.stat().st_size, sha256=h, same_as_physical_baseline=phys.get(rel, {}).get('sha256') == h,
                          baseline_sha256=phys.get(rel, {}).get('sha256')))
    changed = sorted(f['path'][len('/99_LEX_V1/'):] for f in files if f['path'].startswith('/99_LEX_V1/') and not f['same_as_physical_baseline'])
    if tuple(changed) != EXPECTED_CHANGED:
        raise SystemExit(f'UNEXPECTED_DIFF_VS_PHYSICAL_BASELINE {changed}')
    tested = {rel: trees[0].get(rel) == want for rel, want in PHYSICALLY_TESTED.items()}
    if not all(tested.values()):
        raise SystemExit(f'PROMOTION_BYTES_NOT_PHYSICALLY_TESTED {tested}')
    m = json.loads((OUT / 'SD/99_LEX_V1/00_SYS/LEX_DEVICE_MANIFEST.json').read_text(encoding='utf-8'))
    man_ok = all(trees[0].get(k) == v['sha256'] for k, v in m['files'].items() if k != '99_LEX_V1/00_SYS/LEX_DEVICE_MANIFEST.json')
    report = dict(profile=PROFILE, promotion='C3B2_CORRELATA', staging=OUT.relative_to(ROOT).as_posix(), build_id=man['build_id'],
                  git_commit=man['git_commit'], reference_engine=ENGINE_VERSION, deterministic_runs=a.runs, byte_identical_rebuild=True,
                  promotion_bytes_match_physical_test=tested, targets_r_only_divergence_vs_generator=rec['targets_r_only_divergence_vs_generator'],
                  device_manifest_matches_package=man_ok, changed_vs_physical_baseline=changed,
                  relations_v2_replace=sorted(r for r in PHYSICALLY_TESTED if r.startswith('99_RELATIONS_V2/')),
                  firmware_change='NONE (SD only)', file_count=len(files), files=files)
    (OUT / '_host').mkdir(exist_ok=True)
    (OUT / '_host/STAGING_FILE_MANIFEST.json').write_bytes((json.dumps(report, ensure_ascii=False, indent=1) + '\n').encode('utf-8'))
    print(json.dumps({k: v for k, v in report.items() if k != 'files'}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
