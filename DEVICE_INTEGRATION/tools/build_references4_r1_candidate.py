"""REFERÊNCIAS Nº 4 R1: HOST-ONLY SD candidate = physically approved C3B.2 package + RUN5 (two WORK_REFERENCE approvals), built with the
OFFICIAL staging generator (build_sd_staging), exactly as the C3B.2 promotion was built (same profile, ENTENDA chain, runtime, TEXT_MAP).

  - REF_LOOKUP.IDX / REF_PAYLOAD.IDX: RUN5 bytes (LEGAL_TARGET_ID/derived/export_test/run5_references4_r1_candidate/device_ready, committed blobs).
  - CF88_TARGETS.IDX: RUN5 bytes (C3B.2 + W recomputed). The generator recomputes every flag; the RUN5 file may differ from that
    recomputation ONLY in position R ([4], not read by the firmware), which C3B.2 kept on purpose. Any other difference stops the build.
  - 99_RELATIONS_V2 (RELACOES/REL_LOOKUP/EXT_ARTIGOS): C3B.2 bytes, unchanged.
  - LEXV1.VER / LEX_DEVICE_MANIFEST.json: regenerated by the generator (GIT_COMMIT pinned with --commit to the commit holding the RUN5 bytes).
Proof first: the official C3B.2 promotion build is re-run and must reproduce the approved C3B.2 staging tree (STAGING_FILE_MANIFEST.json).
Outputs: DEVICE_INTEGRATION/staging_sd_v1_references4_r1_candidate/ (full SD tree, gitignored) and the package
REFERENCES_4_FINAL_CANDIDATE_HOST_ONLY/ (only the changed SD files, rollback = C3B.2 bytes, manifests, diff). Never writes to a removable volume.
Usage: python build_references4_r1_candidate.py --commit <sha> [--runs N]
"""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DI = HERE.parent
ROOT = DI.parent
sys.path.insert(0, str(HERE))
import build_sd_staging as S  # noqa: E402
import build_c3b2_promotion_candidate as C  # noqa: E402

PROFILE = C.PROFILE
RUN5 = ROOT / 'LEGAL_TARGET_ID/derived/export_test/run5_references4_r1_candidate'
RUN5_DEV = RUN5 / 'device_ready'
OUT = DI / 'staging_sd_v1_references4_r1_candidate'
TMP = DI / '_tmp_references4_r1_rebuild'
TMP_C3B2 = DI / '_tmp_c3b2_reproduction'
PKG = ROOT / 'REFERENCE_COVERAGE_AUDIT/REFERENCES_4_FINAL_CANDIDATE_HOST_ONLY'
C3B2_STAGING = DI / 'C3B2_CORRELATA_PROMOTION/STAGING_FILE_MANIFEST.json'
ENGINE_VERSION = dict(tag='cf-reference-engine-run5-references4-r1', run='run5', status='RUN5_REFERENCES4_R1_CANDIDATE_HOST_ONLY',
                      derived_from='run4 (C3B.2 physically approved) + WORK_REFERENCE overlay REFERENCES_4_R1 (P20, P21)')
R_POS = 4
EXPECTED_CHANGED = ('99_LEX_V1/00_SYS/LEXV1.VER', '99_LEX_V1/00_SYS/LEX_DEVICE_MANIFEST.json', '99_LEX_V1/10_TARGETS/CF88_TARGETS.IDX',
                    '99_LEX_V1/20_REFERENCES/REF_LOOKUP.IDX', '99_LEX_V1/20_REFERENCES/REF_PAYLOAD.IDX')


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def tree(d):
    return {p.relative_to(d).as_posix(): sha(p) for p in sorted(Path(d).rglob('*')) if p.is_file()}


def c3b2_baseline():
    return {f['path'].lstrip('/'): f['sha256'] for f in json.loads(C3B2_STAGING.read_text(encoding='utf-8'))['files']}


def c3b2_reproduced():
    """The official C3B.2 promotion build, re-run now, gives the approved C3B.2 SD tree byte for byte."""
    try:
        C.build(TMP_C3B2)
        return tree(TMP_C3B2 / 'SD') == c3b2_baseline()
    finally:
        shutil.rmtree(TMP_C3B2, ignore_errors=True)


def build(out, commit):
    run5_targets = (RUN5_DEV / 'CF88_TARGETS.IDX').read_bytes()
    original = S.build_targets
    record = {}

    def targets_with_run5_bytes(sd, idx, status, entenda_lookup, ref_lookup):
        stats = original(sd, idx, status, entenda_lookup, ref_lookup)
        p = sd / '10_TARGETS/CF88_TARGETS.IDX'
        gen, cand = p.read_bytes().decode('utf-8').split('\n'), run5_targets.decode('utf-8').split('\n')
        if len(gen) != len(cand):
            raise SystemExit('TARGETS_SHAPE_DIFFERS')
        r_only = []
        for g, c in zip(gen, cand):
            if g == c:
                continue
            fg, fc = g.split('|'), c.split('|')
            if g.startswith('#') or fg[:3] != fc[:3] or fg[3][:R_POS] != fc[3][:R_POS] or fg[3][R_POS + 1:] != fc[3][R_POS + 1:]:
                raise SystemExit(f'TARGETS_DIFFER_BEYOND_R {fg[0]}')
            r_only.append(fg[0])
        p.write_bytes(run5_targets)
        record['targets_r_only_divergence_vs_generator'] = r_only
        return stats

    S.build_targets = targets_with_run5_bytes
    try:
        man = S.build(out, ref_dir=RUN5_DEV, require_committed_refs=True, reference_engine_version=ENGINE_VERSION, profile=PROFILE,
                      build_commit=commit)
    finally:
        S.build_targets = original
    rel_dir = Path(out) / 'SD/99_RELATIONS_V2/05_INDICES_ESP32_V2'
    rel_dir.mkdir(parents=True)
    for name in ('RELACOES.IDX', 'REL_LOOKUP.IDX', 'EXT_ARTIGOS.IDX'):
        (rel_dir / name).write_bytes((RUN5_DEV / name).read_bytes())
    return man, record


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--commit', required=True)
    ap.add_argument('--runs', type=int, default=2)
    a = ap.parse_args()
    if not c3b2_reproduced():
        raise SystemExit('C3B2_BASELINE_NOT_REPRODUCED')
    man, rec = build(OUT, a.commit)
    trees = [tree(OUT / 'SD')]
    try:
        for _ in range(a.runs - 1):
            build(TMP, a.commit)
            trees.append(tree(TMP / 'SD'))
    finally:
        shutil.rmtree(TMP, ignore_errors=True)
    if not all(t == trees[0] for t in trees):
        raise SystemExit('STAGING_NOT_DETERMINISTIC')
    base = c3b2_baseline()
    if set(trees[0]) != set(base):
        raise SystemExit('FILE_SET_DIFFERS_FROM_C3B2')
    changed = tuple(sorted(k for k in trees[0] if trees[0][k] != base[k]))
    if changed != EXPECTED_CHANGED:
        raise SystemExit(f'UNEXPECTED_DIFF_VS_C3B2 {changed}')
    for name, rel in (('REF_LOOKUP.IDX', '99_LEX_V1/20_REFERENCES/REF_LOOKUP.IDX'), ('REF_PAYLOAD.IDX', '99_LEX_V1/20_REFERENCES/REF_PAYLOAD.IDX'),
                      ('CF88_TARGETS.IDX', '99_LEX_V1/10_TARGETS/CF88_TARGETS.IDX')):
        if trees[0][rel] != sha(RUN5_DEV / name):
            raise SystemExit(f'STAGING_NOT_RUN5 {rel}')
    m = json.loads((OUT / 'SD/99_LEX_V1/00_SYS/LEX_DEVICE_MANIFEST.json').read_text(encoding='utf-8'))
    man_ok = all(trees[0].get(k) == v['sha256'] for k, v in m['files'].items() if k != '99_LEX_V1/00_SYS/LEX_DEVICE_MANIFEST.json')
    # ---- package: only the changed SD files (+ rollback = C3B.2 bytes of the same paths, taken from the approved promotion rebuild)
    if PKG.exists():
        shutil.rmtree(PKG)
    C.build(TMP_C3B2)
    try:
        for rel in changed:
            for kind, src in (('candidate', OUT / 'SD' / rel), ('rollback', TMP_C3B2 / 'SD' / rel)):
                dst = PKG / kind / 'SD' / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes(Path(src).read_bytes())
    finally:
        shutil.rmtree(TMP_C3B2, ignore_errors=True)
    for rel in changed:
        if sha(PKG / 'rollback/SD' / rel) != base[rel]:
            raise SystemExit(f'ROLLBACK_NOT_C3B2 {rel}')
    diff = [dict(path='/' + rel, before_sha256=base[rel], before_bytes=(PKG / 'rollback/SD' / rel).stat().st_size,
                 after_sha256=trees[0][rel], after_bytes=(PKG / 'candidate/SD' / rel).stat().st_size) for rel in changed]
    report = dict(profile=PROFILE, package='REFERENCES_4_R1', status='HOST_ONLY_CANDIDATE', physical_approved=False, card_touched=False,
                  device_flashed=False, staging=OUT.relative_to(ROOT).as_posix(), build_id=man['build_id'], git_commit=man['git_commit'],
                  reference_engine=ENGINE_VERSION, c3b2_baseline_reproduced=True, deterministic_runs=a.runs, byte_identical_rebuild=True,
                  targets_r_only_divergence_vs_generator=rec['targets_r_only_divergence_vs_generator'],
                  device_manifest_matches_package=man_ok, changed_vs_c3b2=list(changed), unchanged_vs_c3b2=sorted(set(base) - set(changed)),
                  file_diff=diff, file_count=len(trees[0]),
                  files=[dict(path='/' + k, sha256=v, same_as_c3b2=base[k] == v) for k, v in trees[0].items()])
    (PKG / 'REFERENCES_4_R1_PACKAGE_MANIFEST.json').write_bytes((json.dumps(report, ensure_ascii=False, indent=1) + '\n').encode('utf-8'))
    (OUT / '_host').mkdir(exist_ok=True)
    (OUT / '_host/STAGING_FILE_MANIFEST.json').write_bytes((json.dumps(report, ensure_ascii=False, indent=1) + '\n').encode('utf-8'))
    print(json.dumps({k: v for k, v in report.items() if k not in ('files', 'unchanged_vs_c3b2')}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
